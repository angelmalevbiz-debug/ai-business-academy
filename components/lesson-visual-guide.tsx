const phases = ["Вход", "Действие", "Проверка"] as const;

export function LessonVisualGuide({ lessonId }: { lessonId: string }) {
  const [selected, setSelected] = useState(0);
  const id = useId();
  const steps = guides[lessonId];
  if (!steps) return null;
  const current = steps[selected];
  const CurrentIcon = current.icon;

  return (
    <section className={styles.guide} aria-labelledby={`${id}-heading`}>
      <div className={styles.heading}>
        <h2 id={`${id}-heading`}>Виж го с пример</h2>
      </div>
      <ol className={styles.flow}>
        {steps.map((step, index) => {
          const StepIcon = step.icon;
          return (
            <li key={step.title}>
              <button
                type="button"
                className={selected === index ? styles.selected : ""}
                id={`${id}-step-${index}`}
                aria-pressed={selected === index}
                aria-controls={`${id}-explanation`}
                onClick={() => setSelected(index)}
              >
                <span className={styles.phase}>
                  <StepIcon size={28} weight="duotone" aria-hidden="true" />
                  {phases[index]}
                </span>
              </button>
              {index < steps.length - 1 && (
                <ArrowRight
                  className={styles.connector}
                  size={20}
                  aria-hidden="true"
                />
              )}
            </li>
          );
        })}
      </ol>
      <div
        className={styles.explanation}
        id={`${id}-explanation`}
        role="region"
        aria-labelledby={`${id}-step-${selected}`}
        aria-live="polite"
        aria-atomic="true"
      >
        <CurrentIcon size={34} weight="regular" aria-hidden="true" />
        <div className={styles.currentExample} key={selected}>
          <h3>{current.title}</h3>
          <p>{current.example}</p>
          <details><summary>Защо тази стъпка?</summary><p>{current.explanation}</p></details>
        </div>
      </div>
    </section>
  );
}
